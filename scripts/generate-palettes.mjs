#!/usr/bin/env node
/**
 * Writes the palette stylesheets: src/styles/palettes/<name>.css for every palette of src/palettes.ts and index.css that
 * imports them all. The CSS is paletteCss() of src/palette.ts, the same code `applyTaoPalette()` runs in the browser;
 * a test keeps these files equal to what it produces. Run it after changing a palette or the palette logic:
 *
 *   npm run palettes
 */
import { createRequire } from 'node:module';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { build } = createRequire(join(root, 'package.json'))('esbuild');

// the logic is TypeScript: bundle it into a throw-away folder and import the result
const tmp = mkdtempSync(join(tmpdir(), 'taoui-palettes-'));
try {
    await build({
        entryPoints: { palette: join(root, 'src/palette.ts'), palettes: join(root, 'src/palettes.ts') },
        bundle: true,
        splitting: true,
        format: 'esm',
        platform: 'node',
        outdir: tmp,
        logLevel: 'error',
    });
    const { paletteCss } = await import(pathToFileURL(join(tmp, 'palette.js')).href);
    const { taoPalettes } = await import(pathToFileURL(join(tmp, 'palettes.js')).href);

    const dir = join(root, 'src/styles/palettes');
    mkdirSync(dir, { recursive: true });
    for (const def of taoPalettes) {
        writeFileSync(join(dir, `${def.name}.css`), paletteCss(def));
    }
    const index = [
        '/**',
        ' * Tao UI palettes: all of them. Import this file, or only the palette you use (`./sunset.css`).',
        ' * Generated by `npm run palettes`.',
        ' */',
        ...taoPalettes.map((def) => `@import "./${def.name}.css";`),
        '',
    ].join('\n');
    writeFileSync(join(dir, 'index.css'), index);
    console.log(`${taoPalettes.length} palettes written to src/styles/palettes/`);
} finally {
    rmSync(tmp, { recursive: true, force: true });
}
